create table jobs (
    id uuid primary key,
    job_type varchar(80) not null,
    status varchar(20) not null,
    stage varchar(80),
    created_at timestamp with time zone not null,
    started_at timestamp with time zone,
    finished_at timestamp with time zone,
    exit_code integer,
    error_code varchar(120),
    error_message varchar(2000)
);

create table job_output_lines (
    id bigint generated by default as identity primary key,
    job_id uuid not null,
    sequence_no bigint not null,
    stream varchar(10) not null,
    content varchar(4000) not null,
    emitted_at timestamp with time zone not null,
    constraint fk_job_output_job foreign key (job_id) references jobs(id),
    constraint uk_job_output_sequence unique (job_id, sequence_no)
);

create index ix_job_output_job_sequence on job_output_lines(job_id, sequence_no);
